/* ==================================================================
   home-greet.js · 按时间变化的问候语（零基础自学版）
   ------------------------------------------------------------------
   【这个脚本是干什么的】
     首页有一行"你好，我是"，这个脚本会根据当前时间自动改成：
       5:00-11:00  → "早上好，我是"
       11:00-13:00 → "中午好，我是"
       13:00-18:00 → "下午好，我是"
       18:00-23:00 → "晚上好，我是"
       23:00-5:00  → "夜深了，我是"
     让网站有"生命感"——不同时间打开看到不同的问候。

   【怎么工作的】
     1. 读取用户电脑的当前时间（小时数）
     2. 根据小时数判断是哪个时段
     3. 找到首页 id="greet" 的元素，替换它的文字

   【无依赖】
     纯原生 JavaScript，不需要任何库。
     找不到 #greet 元素时静默退出（不会报错）。

   灵感来自 lvy010 首页的 "Good Night I'm lvy, Nice to meet you!"
   ================================================================== */

// 用 IIFE（立即执行函数表达式）包裹，避免变量污染全局作用域
// 写法：(function(){ ... })();  定义后立即执行
(function () {

  // 根据小时数返回对应的问候语
  function greet() {
    // new Date() 获取当前时间，.getHours() 得到小时数（0-23）
    var h = new Date().getHours();

    // 用 if 链判断时段（注意区间是左闭右开：>= 起始，< 结束）
    if (h >= 5 && h < 11) return "早上好";    // 5点到11点
    if (h >= 11 && h < 13) return "中午好";   // 11点到13点
    if (h >= 13 && h < 18) return "下午好";   // 13点到18点
    if (h >= 18 && h < 23) return "晚上好";   // 18点到23点
    return "夜深了";                           // 23点到次日5点
  }

  // 把问候语写入页面
  function apply() {
    // 找到首页 id="greet" 的元素（就是"你好，我是"那行）
    var el = document.getElementById("greet");

    // 如果找到了（首页才有这个元素，内容页没有）
    if (el) {
      // 替换文字内容：问候语 + "，我是"
      // 比如早上变成："早上好，我是"
      el.textContent = greet() + "，我是";
    }
    // 如果没找到（不是首页），什么都不做
  }

  // 确保在 DOM 加载完成后执行
  // 如果页面还在加载中，等 DOMContentLoaded 事件触发后再执行
  // 如果已经加载完成，直接执行
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", apply);
  } else {
    apply();
  }

})();
